export const categoryIconKey = (name: string) => name.trim().toLowerCase().replace(/[\s:()’'/_-]+/g, "");
export const DEFAULT_CATEGORY_IMAGE = "/category-icons/receipt.webp";

/** Accounts are drawn by their Notion "Account Type"; the emoji on the account page is ignored here. */
const ACCOUNT_IMAGE_BY_TYPE: Record<string, string> = { checking: "credit-card", joined: "family", saving: "piggy-bank" };
export const accountIconSource = (type?: string | null) => `/category-icons/${ACCOUNT_IMAGE_BY_TYPE[type?.trim().toLowerCase() ?? ""] ?? "bank"}.webp`;

/** Explicit image sources win; names distinguish categories sharing the same old emoji. */
export function categoryIconSource(icon?: string | null, name?: string | null): string {
  if (icon && /^\/category-icons\/[a-z0-9-]+\.webp$/.test(icon)) return icon;
  if (icon?.startsWith("https://")) return icon;
  const slug = (name ? CATEGORY_IMAGE_BY_NAME[categoryIconKey(name)] : undefined) ?? (icon ? IMAGE_BY_EMOJI[icon.trim()] : undefined);
  return slug ? `/category-icons/${slug}.webp` : DEFAULT_CATEGORY_IMAGE;
}
